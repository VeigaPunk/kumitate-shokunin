#!/usr/bin/env node
/**
 * attest51-probe.mjs — FROZEN counter for kumitate round 51, claim C1 (rule `A51`), v3.
 *
 *   node .ufo/waves/round-51/probe/attest51-probe.mjs <lane> <rev>
 *
 * Freeze history (all repairs named in plan.md `## Freeze repair addendum`):
 *   v1 06ecbf47 — comment-termination syntax error: the v1 JSDoc contained a glob whose
 *       star-slash sequence closed the block comment early; the probe could not execute
 *       (SyntaxError) and a crash reads exit 1, indistinguishable from a legitimate UNMET.
 *       Found by seat CritC1 before any data ran against it.
 *   v2 1fd8aceb — comment repaired; D51's sibling column bug repaired separately (3ed875d3).
 *   v3 <this> — seat CritC1 demonstrated a verdict-printing stub clears v2's A1..A4 (the
 *       plan's declared do-nothing kill rule failed). v3 adds two behavioural challenge arms
 *       (A2c, A3c) that bind receipts to a probe-issued command's real argv and output hash;
 *       no print-stub can satisfy them without actually running commands and hashing their
 *       output. Check set and predicate label unchanged in kind: ATTEST_HELD = every check
 *       holds. Before-state re-measured at base with v3: instrument absent -> UNMET.
 *
 * Scores seven checks over the committed bytes of <rev> (extracted with `git archive`, never
 * the working tree):
 *   A1  scripts/receipt-attest.mjs exists at rev and `node scripts/receipt-attest.mjs
 *       --selftest` exits 0 with final line `ATTEST_SELFTEST: PASS`.
 *   A2  the three committed receipts .ufo/waves/round-51/receipts/attest-run-{1,2,3}.txt
 *       (+ .sha256 sidecars) each verify `RECEIPT: VALID` exit 0; embedded nonces pairwise
 *       distinct; file sha256 pairwise distinct; max(run-at) - min(run-at) >= 300 s from
 *       the `run-at:` prelude lines.
 *   A2c CHALLENGE (v3): the probe itself runs `node scripts/receipt-attest.mjs run --out
 *       <tmp> -- /usr/bin/printf %s <probe-nonce>` at the extracted rev; the fresh receipt
 *       must verify VALID, its argv must end with the probe nonce and its stdout sha256 must
 *       equal sha256(<probe-nonce bytes>) — a stub that only prints verdict strings cannot
 *       produce a receipt binding a command it never ran.
 *   A3  the committed doctored control attest-run-2-replayed.txt (run-2's receipt with
 *       only the `run-at:` prelude rewritten, sidecar untouched — the lesson-M2 forgery)
 *       verifies `RECEIPT: TAMPERED` exit 1.
 *   A3c CHALLENGE (v3): the probe runs `run` for a fresh receipt, copies it, rewrites ONLY
 *       the `run-at:` prelude (sidecar untouched) and requires `verify` to answer
 *       `RECEIPT: TAMPERED` exit 1 — the M2 forgery against live-generated bytes.
 *   A4  no nonce reuse: the ledger arm — every pair of the three round-51 receipts passes
 *       `verify --ledger <receipts-dir>`, and each embedded nonce appears in NO prior
 *       receipt corpus file under .ufo/waves/ (round-48/49/50 receipt corpora) at rev (the
 *       sweep prints what it scanned; zero hits required).
 *   A4c REPLAY CHALLENGE (v3r5) — the probe crafts a twin of a live-generated receipt whose
 *       semantic body is altered (argv suffixed) and whose inner digest is recomputed per
 *       the contract (canonical JSON, sorted keys, digest field removed), with a recomputed
 *       sidecar; the twin alone must verify VALID, and `verify --ledger` over a directory
 *       containing both the original and the twin must answer `RECEIPT: REPLAY` exit 1 —
 *       the declared nonce-reuse class must be asserted, not just implied.
 *   A3d DIGEST-BINDING CHALLENGE (v3r6, seat DistWave1 item 1) — a receipt whose inner
 *       digest field is corrupted (constant hex, semantic body untouched) but whose sidecar
 *       is recomputed must NOT read VALID: `verify` must answer `RECEIPT: REPLAY` exit 1 —
 *       otherwise a tool that checks only sidecars passes every arm.
 *   A5  pin.receipt-attest in the SCORECARD.md `kumitate-gate-pins-v1` block equals the
 *       sha256 of the extracted scripts/receipt-attest.mjs, and
 *       `node scripts/proxy-check.mjs --strict` (UFO_SRC = live origin checkout) exits 0
 *       with `PROXY: MATCH`.
 *
 * Predicate ATTEST_HELD = held=9/9, exit 0. Any other reading is `ATTEST_UNMET held=<k>/9`
 * exit 1. A crash or an unreadable extraction is exit 2 (never a score); a malformed verdict
 * line from the tool simply fails its check's pattern (a MISS, not a crash). Frozen at
 * `.ufo/waves/round-51/plan.md` § C1 + `## Freeze repair addendum` before any data seat ran
 * against the v3r6 arms.
 */
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createHash, randomBytes } from 'node:crypto';

const RULE = 'A51';
const VERSION = 'v3';
const ORIGIN = '/home/vgpnk/Projects/ufo-fsd-alpha';
const RECEIPTS = ['attest-run-1.txt', 'attest-run-2.txt', 'attest-run-3.txt'];
const RDIR = '.ufo/waves/round-51/receipts';
const [laneArg, rev, ...rest] = process.argv.slice(2);
if (!laneArg || !rev || rest.length) {
  process.stderr.write('ATTEST51: USAGE node attest51-probe.mjs <lane> <rev>\n');
  process.exit(64);
}
const lane = resolve(laneArg);
if (!existsSync(join(lane, '.git'))) {
  process.stderr.write(`ATTEST51: USAGE ${JSON.stringify(lane)} is not a git repo\n`);
  process.exit(64);
}

const sha = (b) => createHash('sha256').update(b).digest('hex');
const sh = (cmd, args, opts = {}) =>
  spawnSync(cmd, args, { encoding: 'utf8', timeout: 240_000, maxBuffer: 64 << 20, ...opts });

const T = mkdtempSync(join(tmpdir(), 'a51-probe.'));
const checks = [];
const hold = (id, ok, detail) => checks.push({ id, ok, detail });
const lastLine = (r) => `${r.stderr || ''}${r.stdout || ''}`.trim().split('\n').pop() || '';
try {
  const tar = spawnSync('bash', ['-lc',
    `git -C ${JSON.stringify(lane)} archive ${JSON.stringify(rev)} | tar -x -C ${JSON.stringify(T)}`],
    { encoding: 'utf8', timeout: 180_000 });
  if (tar.status !== 0) {
    process.stderr.write(`ATTEST51: FAIL-CLOSED git archive ${rev} exit=${tar.status}\n`);
    process.exit(2);
  }
  const S = join(T, 'scripts');
  const tool = join(S, 'receipt-attest.mjs');
  const runTool = (args) => sh('node', [tool, ...args], { cwd: T });

  // A1
  let a1ok = false; let a1d = '';
  if (existsSync(tool)) {
    const r = runTool(['--selftest']);
    const last = lastLine(r);
    a1ok = r.status === 0 && /ATTEST_SELFTEST: PASS/.test(last);
    a1d = a1ok ? 'selftest PASS' : `exit=${r.status} last=${JSON.stringify(last.slice(0, 120))}`;
  } else {
    a1d = 'scripts/receipt-attest.mjs absent';
  }
  hold('A1', a1ok, a1d);

  // A2 (+A3, A4 distinctness/ledger) over the committed round-51 receipts
  const rd = join(T, RDIR);
  const nonces = []; const runats = []; const fshas = [];
  let a2ok = true; const a2miss = [];
  for (const f of RECEIPTS) {
    const p = join(rd, f);
    const side = `${p}.sha256`;
    if (!existsSync(p) || !existsSync(side)) { a2ok = false; a2miss.push(`${f}:absent`); continue; }
    const v = runTool(['verify', p]);
    const last = lastLine(v);
    if (!(v.status === 0 && /RECEIPT: VALID/.test(last))) { a2ok = false; a2miss.push(`${f}:exit=${v.status} ${last.slice(0, 80)}`); continue; }
    let nonce = null; let runat = null;
    try {
      const jsonLine = readFileSync(p, 'utf8').split('\n').find((l) => l.trimStart().startsWith('{'));
      const j = JSON.parse(jsonLine);
      nonce = j.nonce; runat = j.wall_start || null;
    } catch (e) { a2ok = false; a2miss.push(`${f}:unparseable(${e.message})`); }
    const pre = readFileSync(p, 'utf8').split('\n').find((l) => l.startsWith('run-at:'));
    if (pre) runat = pre.slice('run-at:'.length).trim();
    if (!nonce || !runat) { a2ok = false; a2miss.push(`${f}:nonce/run-at missing`); continue; }
    nonces.push(nonce); runats.push(Date.parse(runat)); fshas.push(sha(readFileSync(p)));
  }
  let span = 0;
  if (runats.length === 3 && runats.every((t) => Number.isFinite(t))) span = (Math.max(...runats) - Math.min(...runats)) / 1000;
  const distinctN = new Set(nonces).size === nonces.length && nonces.length === 3;
  const distinctS = new Set(fshas).size === fshas.length && fshas.length === 3;
  if (a2ok && (!distinctN || !distinctS || span < 300)) {
    a2ok = false;
    if (!distinctN) a2miss.push('nonce-not-distinct');
    if (!distinctS) a2miss.push('sha-not-distinct');
    if (span < 300) a2miss.push(`span=${Math.round(span)}s<300`);
  }
  hold('A2', a2ok, a2ok ? `3 receipts VALID span=${Math.round(span)}s nonces=distinct sha=distinct` : a2miss.join(';'));

  // A2c — challenge: run must bind a probe-issued command's argv and output hash
  let a2cok = false; let a2cd = '';
  if (existsSync(tool)) {
    const nonce = `a51c-${randomBytes(8).toString('hex')}`;
    const base = join(T, `challenge-${nonce}`);
    const r = runTool(['run', '--out', base, '--', '/usr/bin/printf', '%s', nonce]);
    const rcpt = `${base}.txt`;
    if (r.status !== 0 || !existsSync(rcpt)) {
      a2cd = `run exit=${r.status} last=${JSON.stringify(lastLine(r).slice(0, 100))}`;
    } else {
      const v = runTool(['verify', rcpt]);
      let j = null;
      try {
        const jsonLine = readFileSync(rcpt, 'utf8').split('\n').find((l) => l.trimStart().startsWith('{'));
        j = JSON.parse(jsonLine);
      } catch (e) { a2cd = `challenge receipt unparseable: ${e.message}`; }
      const argvOk = j && Array.isArray(j.argv) && j.argv[j.argv.length - 1] === nonce;
      const outOk = j && (j.stdout_sha256 === sha(Buffer.from(nonce, 'utf8')) || j.stdout_sha256 === sha(Buffer.from(`${nonce}`, 'utf8')) || (j.stdout_sha256 === sha(Buffer.from(nonce))));
      const validOk = v.status === 0 && /RECEIPT: VALID/.test(lastLine(v));
      const sideOk = sh('/usr/bin/sha256sum', ['-c', `${rcpt}.sha256`], { cwd: T }).status === 0;
      a2cok = Boolean(argvOk && outOk && validOk && sideOk);
      a2cd = a2cok ? `challenge bound argv+stdout(${nonce.slice(0, 10)}) sha256sum -c ok`
        : `argvOk=${argvOk} outOk=${outOk} validOk=${validOk} sideOk=${sideOk}`;
    }
  } else a2cd = 'tool absent';
  hold('A2c', a2cok, a2cd);

  // A3 — committed doctored control
  let a3ok = false; let a3d = '';
  const rp = join(rd, 'attest-run-2-replayed.txt');
  if (existsSync(tool) && existsSync(rp)) {
    const v = runTool(['verify', rp]);
    const last = lastLine(v);
    a3ok = v.status === 1 && /RECEIPT: TAMPERED/.test(last);
    a3d = a3ok ? 'prelude-replay rejected' : `exit=${v.status} last=${JSON.stringify(last.slice(0, 120))}`;
  } else a3d = 'attest-run-2-replayed.txt absent';
  hold('A3', a3ok, a3d);

  // A3c — challenge: live-generated prelude-only tamper must read TAMPERED
  let a3cok = false; let a3cd = '';
  if (existsSync(tool)) {
    const base = join(T, `challenge-tamper-${randomBytes(6).toString('hex')}`);
    const r = runTool(['run', '--out', base, '--', '/usr/bin/printf', '%s', 'a51c-tamper']);
    const rcpt = `${base}.txt`;
    if (r.status !== 0 || !existsSync(rcpt)) {
      a3cd = `run exit=${r.status}`;
    } else {
      const tampered = `${rcpt}.tampered`;
      const lines = readFileSync(rcpt, 'utf8').split('\n');
      const idx = lines.findIndex((l) => l.startsWith('run-at:'));
      if (idx === -1) {
        a3cd = 'no run-at prelude in generated receipt';
      } else {
        lines[idx] = 'run-at: 2020-01-01T00:00:00.000Z (rewritten by probe A3c)';
        writeFileSync(tampered, lines.join('\n'));
        // the M2 forgery keeps the GENUINE sidecar: copy it unchanged so A3c tests
        // prelude-rewrite + untouched-sidecar (not the missing-sidecar class).
        if (existsSync(`${rcpt}.sha256`)) copyFileSync(`${rcpt}.sha256`, `${tampered}.sha256`);
        const v = runTool(['verify', tampered]);
        const last = lastLine(v);
        a3cok = v.status === 1 && /RECEIPT: TAMPERED/.test(last);
        a3cd = a3cok ? 'live prelude-tamper rejected' : `exit=${v.status} last=${JSON.stringify(last.slice(0, 120))}`;
      }
    }
  } else a3cd = 'tool absent';
  hold('A3c', a3cok, a3cd);

  // A4
  let a4ok = true; const a4d = [];
  if (existsSync(tool) && existsSync(rd)) {
    for (const f of RECEIPTS) {
      const p = join(rd, f);
      if (!existsSync(p)) { a4ok = false; a4d.push(`${f}:absent`); continue; }
      const v = runTool(['verify', '--ledger', rd, p]);
      const last = lastLine(v);
      if (!(v.status === 0 && /RECEIPT: VALID/.test(last))) { a4ok = false; a4d.push(`${f}:ledger exit=${v.status} ${last.slice(0, 80)}`); }
    }
    const prior = [];
    const waves = join(T, '.ufo', 'waves');
    if (existsSync(waves)) {
      const walk = (d) => {
        for (const n of readdirSync(d)) {
          const p = join(d, n);
          let st;
          try { st = statSync(p); } catch { continue; }
          if (st.isDirectory()) { if (!/round-51$/.test(n)) walk(p); continue; }
          if (/receipt|ReRun|L1-score/i.test(n)) prior.push(p);
        }
      };
      walk(waves);
    }
    let hits = 0;
    for (const pp of prior) {
      let txt = '';
      try { txt = readFileSync(pp, 'utf8'); } catch { continue; }
      for (const n of nonces) if (n && txt.includes(n)) hits += 1;
    }
    if (hits > 0) { a4ok = false; a4d.push(`nonce-reuse-in-prior hits=${hits}`); }
    a4d.push(`prior-files=${prior.length}`);
  } else { a4ok = false; a4d.push('tool or receipts dir absent'); }
  hold('A4', a4ok, a4d.join(';'));

  // A4c — REPLAY challenge: craft a same-nonce/different-body twin with a recomputed inner
  // digest (contract canonical form: parsed JSON, digest removed, keys sorted recursively,
  // one line) + recomputed sidecar; twin alone must be VALID; the ledger over {original,
  // twin} must answer REPLAY exit 1 for both.
  let a4cok = false; let a4cd = '';
  if (existsSync(tool)) {
    const sortKeys = (v) => {
      if (Array.isArray(v)) return v.map(sortKeys);
      if (v && typeof v === 'object') {
        return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]));
      }
      return v;
    };
    const base = join(T, `a4c-${randomBytes(6).toString('hex')}`);
    const r = runTool(['run', '--out', base, '--', '/usr/bin/printf', '%s', 'a4c-original']);
    const rcpt = `${base}.txt`;
    if (r.status !== 0 || !existsSync(rcpt) || !existsSync(`${rcpt}.sha256`)) {
      a4cd = `run exit=${r.status}`;
    } else {
      try {
        const lines = readFileSync(rcpt, 'utf8').split('\n');
        const ji = lines.findIndex((l) => l.trimStart().startsWith('{'));
        const body = JSON.parse(lines[ji]);
        const nonce = body.nonce;
        body.argv = [...(body.argv || []), 'a4c-evil-append'];
        const { digest, ...rest } = body;
        const canon = JSON.stringify(sortKeys(rest));
        const twinName = 'a4c-twin.txt';
        const twinPath = join(T, twinName);
        lines[ji] = canon.slice(0, -1) + `,"digest":"${sha(Buffer.from(canon, 'utf8'))}"}`;
        writeFileSync(twinPath, lines.join('\n'));
        writeFileSync(`${twinPath}.sha256`, `${sha(readFileSync(twinPath))}  ${twinName}\n`);
        const vTwin = runTool(['verify', twinPath]);
        const twinValid = vTwin.status === 0 && /RECEIPT: VALID/.test(lastLine(vTwin));
        const ledgerDir = mkdtempSync(join(tmpdir(), 'a4c-ledger.'));
        copyFileSync(rcpt, join(ledgerDir, 'orig.txt'));
        copyFileSync(`${rcpt}.sha256`, join(ledgerDir, 'orig.txt.sha256'));
        copyFileSync(twinPath, join(ledgerDir, twinName));
        copyFileSync(`${twinPath}.sha256`, join(ledgerDir, `${twinName}.sha256`));
        const vL1 = runTool(['verify', '--ledger', ledgerDir, join(ledgerDir, 'orig.txt')]);
        const vL2 = runTool(['verify', '--ledger', ledgerDir, join(ledgerDir, twinName)]);
        const replay1 = vL1.status === 1 && /RECEIPT: REPLAY/.test(lastLine(vL1));
        const replay2 = vL2.status === 1 && /RECEIPT: REPLAY/.test(lastLine(vL2));
        a4cok = twinValid && replay1 && replay2;
        a4cd = `twinValid=${twinValid} ledger(orig)=${replay1 ? 'REPLAY' : lastLine(vL1).slice(0, 60)} ledger(twin)=${replay2 ? 'REPLAY' : lastLine(vL2).slice(0, 60)}`;
        rmSync(ledgerDir, { recursive: true, force: true });
      } catch (e) {
        a4cd = `craft failed: ${e.message}`;
      }
    }
  } else a4cd = 'tool absent';
  hold('A4c', a4cok, a4cd);

  // A3d — DIGEST-BINDING challenge: corrupt only the inner digest field (constant hex),
  // recompute the sidecar; verify must NOT read VALID (expect RECEIPT: REPLAY exit 1).
  let a3dok = false; let a3dd = '';
  if (existsSync(tool)) {
    const base = join(T, `a3d-${randomBytes(6).toString('hex')}`);
    const r = runTool(['run', '--out', base, '--', '/usr/bin/printf', '%s', 'a3d-digest']);
    const rcpt = `${base}.txt`;
    if (r.status !== 0 || !existsSync(rcpt)) {
      a3dd = `run exit=${r.status}`;
    } else {
      try {
        const lines = readFileSync(rcpt, 'utf8').split('\n');
        const ji = lines.findIndex((l) => l.trimStart().startsWith('{'));
        const body = JSON.parse(lines[ji]);
        body.digest = 'f'.repeat(64);
        lines[ji] = JSON.stringify(body);
        const bad = `${rcpt}.baddigest`;
        writeFileSync(bad, lines.join('\n'));
        writeFileSync(`${bad}.sha256`, `${sha(readFileSync(bad))}  ${bad.split('/').pop()}\n`);
        const v = runTool(['verify', bad]);
        const last = lastLine(v);
        a3dok = v.status === 1 && /RECEIPT: REPLAY/.test(last);
        a3dd = a3dok ? 'corrupt-digest rejected as REPLAY' : `exit=${v.status} last=${JSON.stringify(last.slice(0, 100))}`;
      } catch (e) {
        a3dd = `craft failed: ${e.message}`;
      }
    }
  } else a3dd = 'tool absent';
  hold('A3d', a3dok, a3dd);

  // A5
  let a5ok = false; const a5d = [];
  const sc = join(T, 'SCORECARD.md');
  if (existsSync(tool) && existsSync(sc)) {
    const m = /pin\.receipt-attest=([0-9a-f]{64})/.exec(readFileSync(sc, 'utf8'));
    if (!m) a5d.push('pin.receipt-attest absent');
    else if (m[1] !== sha(readFileSync(tool))) a5d.push(`pin ${m[1].slice(0, 8)}!=${sha(readFileSync(tool)).slice(0, 8)}`);
    else a5d.push('pin match');
    const pr = sh('node', [join(S, 'proxy-check.mjs'), '--strict'], { cwd: T, env: { ...process.env, UFO_SRC: ORIGIN } });
    const last = lastLine(pr);
    if (!(pr.status === 0 && /PROXY: MATCH/.test(last))) { a5d.push(`proxy exit=${pr.status} ${last.slice(0, 100)}`); }
    else a5d.push('proxy MATCH');
    a5ok = a5d.length === 2 && a5d[0] === 'pin match' && /proxy MATCH/.test(a5d[1]);
  } else a5d.push('tool or SCORECARD absent');
  hold('A5', a5ok, a5d.join(';'));
} catch (e) {
  process.stderr.write(`ATTEST51: FAIL-CLOSED ${e.stack || e}\n`);
  process.exit(2);
} finally {
  try { rmSync(T, { recursive: true, force: true }); } catch {}
}

const held = checks.filter((c) => c.ok).length;
const label = held === checks.length ? 'ATTEST_HELD' : 'ATTEST_UNMET';
process.stdout.write(`ATTEST51: ${label} held=${held}/${checks.length} checks=${checks.length} rev=${rev} rule=${RULE} version=${VERSION} | ${checks.map((c) => `${c.id} ${c.ok ? 'PASS' : `MISS ${c.detail.slice(0, 80)}`}`).join(' | ')}\n`);
process.exit(held === checks.length ? 0 : 1);
